type ContentProps = { children?: ReactNode; id?: string };
function textContent(node: ReactNode): string {
  if (typeof node === "string" || typeof node === "number") return String(node);
  if (Array.isArray(node)) return node.map(textContent).join("");
  if (!isValidElement<ContentProps>(node)) return "";
  const body = textContent(node.props.children);
  return node.type === "p" || node.type === "li" ? body.trim() + "\n\n" : body;
}

export function publishedLegalDocument(slug: "privacy" | "terms", settings: PublicSettings) {
  const content = slug === "privacy" ? PrivacySections({ settings }) : TermsSections({ settings });
  const sections = Children.toArray(content.props.children).flatMap((section) => {
    if (!isValidElement<ContentProps>(section) || !section.props.id) return [];
    const container = Children.toArray(section.props.children).find(child => isValidElement(child) && child.type === "div");
    if (!isValidElement<ContentProps>(container)) return [];
    const children = Children.toArray(container.props.children);
    return [{ id: section.props.id, title: textContent(children[0]).trim(), body: children.slice(1).map(textContent).join("").trim() }];
  });
  return {
    slug,
    title: slug === "privacy" ? "سياسة الخصوصية" : "الشروط والأحكام",
    effectiveDate: LEGAL_EFFECTIVE_DATE,
    version: LEGAL_DOCUMENT_VERSION,
    sections,
  };
}
