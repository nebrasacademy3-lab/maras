import assert from "node:assert/strict";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { chromium } from "playwright";
const fixture = JSON.parse(readFileSync(".data/qa-fixtures.json", "utf8"));
const origin = "http://127.0.0.1:3100";
if (fixture.origin !== origin) throw new Error("Synthetic loopback fixtures required");
const a = fixture.users.find(u => u.role === "student-a"), b = fixture.users.find(u => u.role === "student-b");
const request = (path, token) => fetch(origin + path, { headers: token ? { cookie: `meras_session=${token}` } : {} });
assert.equal((await request(`/api/ai/jobs/${fixture.study.jobId}`, b.token)).status, 404);
assert.equal((await request(`/api/ai/artifacts/${fixture.study.artifactId}/download`, b.token)).status, 404);
assert.equal((await request(`/api/ai/artifacts/${fixture.study.artifactId}/download`, a.token)).status, 200);
const browser = await chromium.launch({ headless: true });
mkdirSync(".data/study-browser", { recursive: true });
const checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: "ar-SA" });
  await context.addCookies([{ name: "meras_session", value: a.token, domain: "127.0.0.1", path: "/", httpOnly: true, sameSite: "Lax" }]);
  const page = await context.newPage(), errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${origin}/learn/qa-physics`, { waitUntil: "domcontentloaded" });
  await page.getByRole("heading", { name: "ثبّت فهمك بأدوات مراس" }).waitFor();
  assert.equal(await page.getByRole("link", { name: "العودة للوحة الطالب" }).getAttribute("href"), "/dashboard");
  await page.getByRole("button", { name: /اختبر فهمك/ }).waitFor();
  await page.screenshot({ path: ".data/study-browser/learn-light.png", fullPage: true });
  const light = await page.locator(".learning-page").evaluate(el => ({ color: getComputedStyle(el).color, background: getComputedStyle(el).backgroundColor }));
  await page.getByRole("button", { name: "تفعيل الوضع الليلي", exact: true }).click();
  await page.waitForFunction(() => document.documentElement.classList.contains("dark"));
  await page.screenshot({ path: ".data/study-browser/learn-dark.png", fullPage: true });
  const dark = await page.locator(".learning-page").evaluate(el => ({ color: getComputedStyle(el).color, background: getComputedStyle(el).backgroundColor }));
  assert.notDeepEqual(light, dark, "learning theme must actually change");
  await page.getByRole("button", { name: "تفعيل الوضع الفاتح", exact: true }).click();
  checks.push("lesson file cards, dashboard navigation and live light/dark theme switch");
  await page.getByRole("button", { name: /اختبر فهمك/ }).click();
  await page.getByLabel("عدد الأسئلة").selectOption("5");
  await page.getByRole("button", { name: "اختبار من الملف", exact: true }).click();
  await page.getByRole("region", { name: "اختبار ذاتي" }).waitFor({ timeout: 90_000 });
  const quiz = page.getByRole("region", { name: "اختبار ذاتي" });
  for (let i = 0; i < 5; i++) {
    assert.equal(await quiz.getByRole("radiogroup").count(), 1);
    await quiz.getByRole("radio").first().check();
    if (i < 4) await quiz.getByRole("button", { name: "التالي", exact: true }).click();
  }
  await quiz.getByRole("button", { name: "إنهاء الاختبار وعرض النتيجة" }).click();
  await quiz.getByRole("heading", { name: "5 إجابات صحيحة من 5" }).waitFor();
  await page.screenshot({ path: ".data/study-browser/quiz-results.png", fullPage: true });
  let generationRequests = 0;
  const listener = request => { if (/\/api\/ai\/files\/\d+\/actions/.test(request.url()) && request.method() === "POST") generationRequests++; };
  page.on("request", listener);
  await quiz.getByRole("button", { name: "إعادة الاختبار دون توليد جديد" }).click();
  assert.equal(await quiz.getByRole("radio").count(), 4);
  assert.equal(generationRequests, 0);
  page.off("request", listener);
  checks.push("real API queue + cached source, one question card, grading, explanations and zero-request retry");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: ".data/study-browser/learn-phone.png", fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2), "no page-wide horizontal overflow");
  checks.push("390px responsive lesson and quiz layout without horizontal overflow");
  assert.deepEqual(errors, [], "no client runtime exceptions");
  const report = { passed: checks.length + 1, checks: ["job/export ownership enforced over HTTP", ...checks], light, dark, clientExceptions: errors, provider: "cached synthetic test data; no live Gemini", video: "metadata-only fixture; actual playback not claimed" };
  writeFileSync(".data/study-browser/report.json", JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
